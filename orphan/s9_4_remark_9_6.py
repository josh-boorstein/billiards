"""Remark 9.6: at 8/15 the perpendicular direction is not completely periodic; it carries a
component of positive measure without periodic trajectory, in the L1 class, and the leg misses it.

The remark cites Delecroix and Rueth [DR22] for the failure; this script reproduces both halves of
its argument exactly, with `lib/flow.py` (a pure-Python port of the decision procedure [DR22] ran,
flatsurf's intervalxt, over Z[zeta_120]): every component is certified a cylinder or without
periodic trajectory (Boshernitzan, the certificate verified in exact integers), and the Kac mass
balance is asserted exactly on every run.  Triangle (8, 7, 15): V0 = O, V1 = A, V2 = R, side 0 =
OA, side 1 = AR = L1, side 2 = RO = L2.

Statements checked:
  * the L1 class at 8/15 (perpendicular to side 1) has components without periodic trajectory,
    each with a Boshernitzan certificate and positive mass, beside its cylinders;
  * the other class is completely periodic: perpendicular to L2 and perpendicular to OA (one
    direction on the surface at odd Q, since holonomy is generated by pi/Q) every component is a
    cylinder, with the same cylinders in both;
  * that class is the L1 class at 7/15: perpendicular to its L1 every component is a cylinder;
  * the leg misses the minimal component: the cylinders tile every L1 edge exactly, and the branch
    count read off them is n(8/15) = 6, as `lib/partition.py` gives;
  * control: at nine other odd-Q centres (Q = 13, 15, 17) every perpendicular direction is
    completely periodic, so the verdict at 8/15 is not the instrument's default.

Not checked: the census figures (4 of 6 separatrices of the L1 class close) -- the remark reports
them as an independent instrument that agrees, not as a step of the argument.
"""
import os
import sys

from common import HERE, centre, check, done

sys.path.insert(0, os.path.join(HERE, '..', 'lib'))
import flow  # noqa: E402

CONTROLS = [(2, 13), (4, 13), (6, 13), (8, 13), (2, 15), (4, 15), (6, 17), (8, 17), (10, 17)]


def perp(P, Q):
    """The decomposition perpendicular to each side of the triangle of P/Q (sides 0, 1, 2)."""
    abc = (P, Q - P, Q)
    return [flow.decompose(abc, j, cap=20000) for j in flow.perp_dirs(abc)]


def cylinders_only(r):
    return set(r['counts']) == {'cylinder'}


def periods(r):
    return sorted(c['period'] for c in r['components'])


def main():
    print('Remark 9.6 -- 8/15 by exact flow decomposition\n')
    oa, l1, l2 = perp(8, 15)
    free = [c for c in l1['components'] if c['kind'] == 'no_periodic']
    check(f'perp L1 at 8/15: {len(free)} components without periodic trajectory beside '
          f'{l1["counts"].get("cylinder", 0)} cylinders', len(free) > 0)
    masses = ', '.join(f'{c["mass"]:.4f}' for c in free)
    check(f'  each with a Boshernitzan certificate and positive mass ({masses})',
          all(c['cert'] is not None and c['mass'] > 0 for c in free))
    check(f'perp L2 at 8/15: all {l2["counts"].get("cylinder", 0)} components cylinders',
          cylinders_only(l2))
    check('perp OA at 8/15: all cylinders, the same ones (one direction at odd Q)',
          cylinders_only(oa) and periods(oa) == periods(l2))
    _, l1_7, _ = perp(7, 15)
    check('perp L1 at 7/15 (= the L2 class at 8/15): all cylinders', cylinders_only(l1_7))

    nf = flow.n_flow(8, 15)
    check(f'the cylinders tile every L1 edge exactly ({len(nf["tiled"])} edges), n = {nf["n"]}',
          nf['n'] is not None and all(nf['tiled']) and not nf['all_cyl'])
    check('n(8/15) = 6 by the flow and by lib/partition.py',
          nf['n'] == 6 == centre(8, 15, fresh=True)['n'])

    bad = [f'{P}/{Q}' for P, Q in CONTROLS if not all(cylinders_only(r) for r in perp(P, Q))]
    check(f'control: every perpendicular direction completely periodic at {len(CONTROLS)} other '
          f'odd-Q centres' + (f' (fails at {", ".join(bad)})' if bad else ''), not bad)
    done()


if __name__ == '__main__':
    main()
